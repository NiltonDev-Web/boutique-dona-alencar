import { Product } from "@/types/product";

const createDemoProduct = (
  id: string,
  name: string,
  price: number,
  category: string,
  description: string,
  image: string,
  colors: string[],
  sizes: string[] = [],
): Product => {
  const options = [
    ...(sizes.length ? [{ name: "Tamanho", values: sizes }] : []),
    ...(colors.length ? [{ name: "Cor", values: colors }] : []),
  ];
  const combinations = options.reduce<Array<Array<{ name: string; value: string }>>>(
    (current, option) =>
      current.flatMap((combination) =>
        option.values.map((value) => [...combination, { name: option.name, value }]),
      ),
    [[]],
  );
  const variants = combinations.map((variantOptions, index) => ({
    id: `demo-${id}-${index + 1}`,
    title: variantOptions.map((option) => option.value).join(" / ") || "Padrão",
    price,
    available: true,
    options: variantOptions,
  }));

  return {
    id: `demo-${id}`,
    name,
    price,
    image,
    category,
    description,
    colors: colors.length ? colors : undefined,
    sizes: sizes.length ? sizes : undefined,
    inStock: true,
    isDemo: true,
    variants,
  };
};

